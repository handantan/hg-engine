#include "constants/battle_constants.h"
.include "battle_commands.inc"

.data

// PMFG (REQ-TGT-ABL-001): Martyr, called from FAINT_MON. The fainted holder heals its ally on the field
// (battler id xor 2) by max(1, maxHP/4) unless the ally is at full HP or under Heal Block. No-op in singles.

_000:
    CheckAbility CHECK_OPCODE_NOT_HAVE, BATTLER_CATEGORY_FAINTED_MON, ABILITY_MARTYR, _end
    CompareMonDataToValue OPCODE_EQU, BATTLER_RELATIVE_ALLY|BATTLER_CATEGORY_FAINTED_MON, BMON_DATA_HP, 0, _end
    CompareMonDataToValue OPCODE_NEQ, BATTLER_RELATIVE_ALLY|BATTLER_CATEGORY_FAINTED_MON, BMON_DATA_HEAL_BLOCK_TURNS, 0, _end
    UpdateMonDataFromVar OPCODE_GET, BATTLER_RELATIVE_ALLY|BATTLER_CATEGORY_FAINTED_MON, BMON_DATA_MAXHP, BSCRIPT_VAR_CALC_TEMP
    CompareMonDataToVar OPCODE_EQU, BATTLER_RELATIVE_ALLY|BATTLER_CATEGORY_FAINTED_MON, BMON_DATA_HP, BSCRIPT_VAR_CALC_TEMP, _end
    UpdateVar OPCODE_DIV, BSCRIPT_VAR_CALC_TEMP, 4
    CompareVarToValue OPCODE_NEQ, BSCRIPT_VAR_CALC_TEMP, 0, _heal
    UpdateVar OPCODE_SET, BSCRIPT_VAR_CALC_TEMP, 1
_heal:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_HP_CALC, BSCRIPT_VAR_CALC_TEMP
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP, BSCRIPT_VAR_BATTLER_FAINTED
    UpdateVar OPCODE_BITWISE_XOR, BSCRIPT_VAR_MSG_BATTLER_TEMP, 2
    AbilityPopup BATTLER_CATEGORY_FAINTED_MON
    UpdateVar OPCODE_FLAG_ON, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_NO_BLINK
    Call BATTLE_SUBSCRIPT_UPDATE_HP
    // {0} had its HP restored.
    PrintMessage 1396, TAG_NICKNAME_ABILITY, BATTLER_CATEGORY_MSG_BATTLER_TEMP, BATTLER_CATEGORY_MSG_BATTLER_TEMP
    Wait
    WaitButtonABTime 30
_end:
    End
